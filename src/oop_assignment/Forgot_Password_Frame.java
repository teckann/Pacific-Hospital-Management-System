    private void btnConSafetyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConSafetyActionPerformed
        
        String InputQ1 = txtQ1.getText();
        String InputQ2 = txtQ2.getText();
        boolean status = false;

        ArrayList<String[]> dataList = File_Control.readFile("loginData.txt", true);
        
        if (!InputQ1.isEmpty() && !InputQ2.isEmpty()) {
        for (String[] line : dataList){
            if (line[5].equals(InputQ1) && line[7].equals(InputQ2)){
            IdVerifiesPanel.setVisible(false);
            safetyQuestionPanel.setVisible(false);
            resetPasswordPanel.setVisible(true);
            lblIncorrectQ1.setVisible(false);
            lblIncorrectQ2.setVisible(false);
            lblTips.setText("");
            status = true;
            break;
            }
        }
        
        if (status == false) {
            txtQ1.setText("");
            txtQ2.setText("");
            lblIncorrectQ1.setVisible(true);
            lblIncorrectQ2.setVisible(true);
        }
        }
        else {
            JOptionPane.showMessageDialog(this, "Please don't leave any fields empty.");
        }
    }//GEN-LAST:event_btnConSafetyActionPerformed

