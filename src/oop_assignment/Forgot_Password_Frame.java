    private void btnIdVerifyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIdVerifyActionPerformed
        
        boolean IdStatus = false;
        boolean undoneSQ = false;
        String IdEntered = txtIdEnter.getText().trim();
        
        String QuesID1="";
        String QuesID2="";
        String Name;
        

        ArrayList<String[]> dataList = File_Control.readFile("loginData.txt", true);
        ArrayList<String[]> questionList = File_Control.readFile("securityQuestion.txt", true);
        
        for (String[] line : dataList){
            Name = line[2];
            QuesID1 = line[4];
            QuesID2 = line[6];
            if (IdEntered.equals(line[0]) && line[4].equals("-")) {
                undoneSQ = true;
                break;
            }
            else if(IdEntered.equals(line[0])){
                IdStatus = true;
                setUserId(line[0]);
                lblName.setText("Hi, " + Name + "!");
                break;
            }
            else{
               IdStatus = false;
            }
        }
        
        for (String[] line : questionList) {
            if (QuesID1.equals(line[0])) {
                lblforgotQ1.setText(line[1]);
            }
            else if (QuesID2.equals(line[0])) {
                lblforgotQ2.setText(line[1]);
            }
        }
        if (undoneSQ) {
            txtIdEnter.setText("");
            lblIdIncorrect.setVisible(true);
            lblIdIncorrect.setText("Your safety question has not been initialized yet.");
        }
        else if(IdStatus){
            safetyQuestionPanel.setVisible(true);
            IdVerifiesPanel.setVisible(false);
            resetPasswordPanel.setVisible(false);
            lblIdIncorrect.setVisible(false);
        }
        else{
            txtIdEnter.setText("");
            lblIdIncorrect.setVisible(true);
            lblIdIncorrect.setText("ID Incorrect, please try again");
        }
        
        
    }//GEN-LAST:event_btnIdVerifyActionPerformed

