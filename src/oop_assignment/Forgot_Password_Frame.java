    private void btnAActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAActionPerformed
        String newPassword = txtNewPassword.getText().trim();
        String newPassword2 = txtNewPasswordTest.getText().trim();
        boolean status = false;
        boolean repeat = false;
        boolean empty = false;
        boolean same = false;

        if (newPassword.equals(newPassword2)){
            status = true;
        }
        else{
            same = true;
        }

        ArrayList<String[]> dataList = File_Control.readFile("loginData.txt", false);
        
        for (String[] line : dataList){
            if(line[0].equals(UserId) && !(line[3].equals(newPassword))){
                line[3] = newPassword;
            }
            else if(line[3].equals(newPassword)) {
                repeat = true;
            }
            else if(newPassword.isEmpty()){
                empty = true;
            }
        }
        
        if (repeat != true && empty != true && status == true && Validation.password(newPassword)){
            File_Control.writeFile("loginData.txt", dataList);
            JOptionPane.showMessageDialog(this, "Password Update successfully");
            Login_Frame Login_Frame = new Login_Frame();
            Login_Frame.setVisible(true);
            this.hide();
            
            
        }
        else if(empty == true){
            lblTips.setText("Please do not enter an empty password");
            txtNewPassword.setText("");
            txtNewPasswordTest.setText("");
        }
        else if(repeat == true){
            lblTips.setText("Don't enter the same password as old one.");
            txtNewPassword.setText("");
            txtNewPasswordTest.setText("");
            
        }
        else if (!Validation.password(newPassword)) {
            JOptionPane.showMessageDialog(this, "Password must contain at least 8 characters, uppercase, lowercase, number, and special character.");
            lblTips.setText("");
        }
        else if (same == true) {
            txtNewPassword.setText("");
            txtNewPasswordTest.setText("");
            lblTips.setText("Make sure the two entries are consistent.");
        }
        
        
    }//GEN-LAST:event_btnAActionPerformed

