    private void btnCreateAccount6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateAccount6ActionPerformed
        String selectedDoctor = cboDoctor2.getSelectedItem().toString();
        ArrayList<String[]> dataList = File_Control.readFile("doctorData.txt", true);

        for (String[] doctor : dataList) {
            String Name = doctor[1]; 
            String Specialist = doctor[3]; 
            String Experience = doctor[14]; 
            String Qualification = doctor[12]; 
            String Location = doctor[7]; 
            String Languages = doctor[13];
            String PhoneNumber = doctor[9];
            String Email = doctor[2];
            String WorkingDays = doctor[6]; 

            if (selectedDoctor.contains(Name)) {  

                if (doctor[12].equals("-") && doctor[13].equals("-") && doctor[14].equals("-")) {
                    NotAvailable9.setVisible(true);
                    Available2.setVisible(false);
                    break;

                } else {
                    Available2.setVisible(true);
                    NotAvailable9.setVisible(false);
                    
                    lblName3.setText(Name);
                    lblSpecialist2.setText(Specialist);
                    lblExperience3.setText(Experience);
                    lblQualification3.setText(Qualification);
                    lblLocation3.setText(Location);
                    lblLanguage3.setText(Languages);
                    lblPhone2.setText(PhoneNumber);
                    lblEmail2.setText(Email);

                    
                    String[] days = {"Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"};
                    JLabel[] timetableLabels = {lblMonday, lblTuesday, lblWednesday, lblThursday, lblFriday, lblSaturday, lblSunday};

                    
                    for (JLabel lbl : timetableLabels) {
                        lbl.setText(""); 
                    }

                    
                    String[] availableDays = WorkingDays.split("/");
                    for (String d : availableDays) {
                        int dayIndex = Integer.parseInt(d) - 1; // 
                        if (dayIndex >= 0 && dayIndex < timetableLabels.length) {
                            timetableLabels[dayIndex].setText("✓"); 
                        }
                    }

                    break;
                }
            }
        }


                
                        
    }//GEN-LAST:event_btnCreateAccount6ActionPerformed

