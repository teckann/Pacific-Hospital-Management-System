    private void txtSearchIDActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtSearchIDActionPerformed
        String searchTicketID = txtSearchID.getText().trim();

        if (searchTicketID.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a Ticket ID to search.", "Input Required", JOptionPane.WARNING_MESSAGE);
            return;
        }

       
        ArrayList<String[]> ticketDataList = File_Control.readFile("ticketData.txt", true);
        boolean ticketFound = false;

        for (String[] ticket : ticketDataList) {
            if (ticket[0].equals(searchTicketID)) {  // ticket[0] is the ticket ID
                ticketFound = true;

                
                String programID = ticket[1];
                ArrayList<String[]> programDataList = File_Control.readFile("healthcareProgramData.txt", true);

                for (String[] program : programDataList) {
                    if (program[0].equals(programID)) {  
                        String programName = program[2];  
                        String programDate = program[3];  
                        String programTime = program[4]; 
                        String programLocation = program[5];  

                    
                        JOptionPane.showMessageDialog(this,
                            "Ticket ID: " + searchTicketID +
                            "\nProgram: " + programName +
                            "\nDate: " + programDate +
                            "\nTime: " + programTime +
                            "\nLocation: " + programLocation ,
                            "Ticket Details",
                            JOptionPane.INFORMATION_MESSAGE);
                        break;
                    }
                }
                break;
            }
        }

        if (!ticketFound) {
            JOptionPane.showMessageDialog(this, 
                "Invalid Ticket ID: " + searchTicketID + 
                "\nPlease check your Ticket ID and try again.", 
                "Ticket Not Found", 
                JOptionPane.ERROR_MESSAGE);
        }
                                      
    }//GEN-LAST:event_txtSearchIDActionPerformed

