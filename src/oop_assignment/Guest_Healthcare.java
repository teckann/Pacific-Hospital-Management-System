    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String selectedCategory = cboCategory.getSelectedItem().toString();
        String selectedProgram = cboProgram.getSelectedItem().toString();
        ArrayList<String[]> dataList = File_Control.readFile("healthcareProgramData.txt", true);

     
        if (!selectedCategory.equals("      ------ Category ------") && 
            !selectedProgram.equals("        ------ Program ------")) {

            // Show ProgramDetails panel, hide ChooseProgram panel
            ProgramDetails.setVisible(true);
            ChooseProgram1.setVisible(false);

            // Populate program details
            for (String[] program : dataList) {
                String category = program[1]; 
                String name = program[2]; 
                String date = program[3]; 
                String time = program[4]; 
                String location = program[5]; 
                String speaker = program[6];
                String totalCapacity = program[7]; 
                String registered = program[8];    

                if (selectedProgram.contains(name)) {  
                   lblprogramName.setText(name);
                   lblCategory.setText(category);
                   lblDate.setText(date);
                   lblTime.setText(time);
                   lblLocation.setText(location);
                   lblSpeaker.setText(speaker);
                   lblRegistered.setText(registered);
                   lblAvailableSpots.setText(totalCapacity);

                   // Display registered/total format
                   lblRegistered.setText(registered);
                   lblAvailableSpots.setText(totalCapacity);

                   
                   try {
                       int registeredCount = Integer.parseInt(registered);
                       int totalCapacityCount = Integer.parseInt(totalCapacity);

                       if (registeredCount >= totalCapacityCount) {
                           btnRegister.setEnabled(false);
                           btnRegister.setText("Program Full");
                           btnRegister.setBackground(Color.GRAY);
                       } else {
                           btnRegister.setEnabled(true);
                           btnRegister.setText("Register for Program");
                           btnRegister.setBackground(new Color(37, 99, 235));
                       }
                   } catch (NumberFormatException ex) {
                       // Handle case where values are not numbers
                       btnRegister.setEnabled(false);
                       btnRegister.setText("Registration Error");
                       btnRegister.setBackground(Color.ORANGE);
                   }
                }
            }
        } else {
           
            ChooseProgram1.setVisible(true);
            ProgramDetails.setVisible(false);

           
            JOptionPane.showMessageDialog(this, 
                "Please select both a category and a program to view details.", 
                "Selection Required", 
                JOptionPane.INFORMATION_MESSAGE);

    } 

    }//GEN-LAST:event_btnSearchActionPerformed

